package it.unibo.unibodget.view.main;

/**
 * Enumeration of application main navigation contexts.
 */
public enum AppContext {
    /** Main financial overview dashboard context. */
    DASHBOARD,
    /** Live currency converter context. */
    CONVERTER,
    /** Investment portfolio context. */
    INVESTMENTS,
    /** Application settings context. */
    SETTINGS,
    /** Sentinel representing total number of contexts. */
    NUM_CONTEXTS
}
